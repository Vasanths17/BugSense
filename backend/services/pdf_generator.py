"""
pdf_generator.py
────────────────
Generates professional, downloadable PDF audit reports using ReportLab:
  1. Cover & Executive Summary:
     - Project Name, Analysis Date, Overall Health Score, Grade, Status
     - Executive summary text
  2. Issue Summary Table (Counts by Severity & Category)
  3. File-level Code Quality Metrics Table
  4. Detailed Explainable Findings Section (Grouped by Severity: Critical -> High -> Medium -> Low)
     - Renders all 9 fields with wrapped text
  5. Disclaimer & Methodology statement:
     - BugSense performs static code analysis
     - Recommends fixes without modifying original user code
     - Transparently explains limitations (cannot guarantee 100% bug detection)
  6. Numbered canvas with running header & footer.
"""

import io
from datetime import datetime
from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import inch
from reportlab.pdfgen import canvas
from reportlab.platypus import (
    HRFlowable,
    KeepTogether,
    PageBreak,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

from models.finding import AnalysisReport, ExplainedIssue


# ── Running Header & Footer Canvas ───────────────────────────────────────────

class NumberedCanvas(canvas.Canvas):
    """
    Two-pass canvas to add accurate page count (e.g. 'Page X of Y')
    along with running header and footer.
    """
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748b"))

        # Header (pages > 1)
        if self._pageNumber > 1:
            self.drawString(54, letter[1] - 36, "BugSense: Explainable AI-Assisted Software Debugging Report")
            self.setStrokeColor(colors.HexColor("#cbd5e1"))
            self.setLineWidth(0.5)
            self.line(54, letter[1] - 42, letter[0] - 54, letter[1] - 42)

        # Footer
        footer_text = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(letter[0] - 54, 36, footer_text)
        self.drawString(54, 36, "CONFIDENTIAL & PROPRIETARY — Generated by BugSense (Offline Static Analysis)")
        self.setStrokeColor(colors.HexColor("#cbd5e1"))
        self.setLineWidth(0.5)
        self.line(54, 48, letter[0] - 54, 48)

        self.restoreState()


# ── PDF Generation Logic ─────────────────────────────────────────────────────

def generate_pdf_report(report: AnalysisReport) -> bytes:
    """
    Builds a professional multi-page PDF report and returns the bytes.
    """
    buffer = io.BytesIO()

    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        leftMargin=54,
        rightMargin=54,
        topMargin=54,
        bottomMargin=54,
    )

    styles = getSampleStyleSheet()

    # Custom typography
    title_style = ParagraphStyle(
        "DocTitle",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=24,
        leading=28,
        textColor=colors.HexColor("#0f172a"),
        spaceAfter=4,
    )
    subtitle_style = ParagraphStyle(
        "DocSubtitle",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=11,
        leading=14,
        textColor=colors.HexColor("#64748b"),
        spaceAfter=15,
    )
    h1_style = ParagraphStyle(
        "SectionH1",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=14,
        leading=18,
        textColor=colors.HexColor("#1e293b"),
        spaceBefore=14,
        spaceAfter=8,
        keepWithNext=True,
    )
    h2_style = ParagraphStyle(
        "SectionH2",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=11,
        leading=14,
        textColor=colors.HexColor("#334155"),
        spaceBefore=8,
        spaceAfter=4,
        keepWithNext=True,
    )
    body_style = ParagraphStyle(
        "BodyDark",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=9,
        leading=13,
        textColor=colors.HexColor("#334155"),
        spaceAfter=6,
    )
    label_style = ParagraphStyle(
        "FieldLabel",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=8.5,
        leading=11,
        textColor=colors.HexColor("#0f172a"),
    )
    field_style = ParagraphStyle(
        "FieldValue",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=8.5,
        leading=11.5,
        textColor=colors.HexColor("#334155"),
    )
    code_style = ParagraphStyle(
        "CodeSnippet",
        parent=styles["Normal"],
        fontName="Courier",
        fontSize=7.5,
        leading=9.5,
        textColor=colors.HexColor("#e2e8f0"),
    )

    story = []

    # ── 1. Header & Title Block ──────────────────────────────────────────────
    story.append(Paragraph("BugSense Analysis Report", title_style))
    story.append(Paragraph(
        f"Project: <b>{report.project_name}</b> | Generated on {datetime.now().strftime('%Y-%m-%d %H:%M:%S UTC')}",
        subtitle_style
    ))
    story.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor("#2563eb"), spaceAfter=15))

    # ── 2. Health Score & Executive Summary ──────────────────────────────────
    health = report.health_score
    score_val = health.score if health else 100
    grade_val = health.grade if health else "A"
    status_val = health.status if health else "Healthy"

    grade_bg = {
        "A": colors.HexColor("#dcfce7"),
        "B": colors.HexColor("#dbeafe"),
        "C": colors.HexColor("#fef9c3"),
        "D": colors.HexColor("#ffedd5"),
        "F": colors.HexColor("#fee2e2"),
    }.get(grade_val, colors.HexColor("#f1f5f9"))

    grade_text = {
        "A": colors.HexColor("#15803d"),
        "B": colors.HexColor("#1d4ed8"),
        "C": colors.HexColor("#a16207"),
        "D": colors.HexColor("#c2410c"),
        "F": colors.HexColor("#b91c1c"),
    }.get(grade_val, colors.HexColor("#334155"))

    summary_html = (
        f"<b>Executive Summary:</b><br/>"
        f"BugSense performed automated static security, bug detection, and code quality analysis "
        f"across the uploaded project archive. The analysis detected a total of <b>{report.total_issues} issues</b> "
        f"({report.detected_count} confirmed, {report.potential_count} potential heuristics) "
        f"across <b>{len(report.file_metrics)} source files</b>.<br/><br/>"
        f"<b>Health Assessment:</b> {health.explanation if health else 'Clean codebase without major defects.'}"
    )

    exec_table_data = [
        [
            Paragraph(f"<font size=28><b>{score_val}</b></font>/100<br/><b>Grade {grade_val}</b> ({status_val})", ParagraphStyle("ScoreP", parent=styles["Normal"], alignment=1, textColor=grade_text)),
            Paragraph(summary_html, body_style)
        ]
    ]

    exec_table = Table(exec_table_data, colWidths=[1.8 * inch, 5.2 * inch])
    exec_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (0, 0), grade_bg),
        ("BACKGROUND", (1, 0), (1, 0), colors.HexColor("#f8fafc")),
        ("BOX", (0, 0), (-1, -1), 1, colors.HexColor("#cbd5e1")),
        ("INNERGRID", (0, 0), (-1, -1), 1, colors.HexColor("#cbd5e1")),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("TOPPADDING", (0, 0), (-1, -1), 10),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 10),
        ("LEFTPADDING", (0, 0), (-1, -1), 10),
        ("RIGHTPADDING", (0, 0), (-1, -1), 10),
    ]))
    story.append(exec_table)
    story.append(Spacer(1, 14))

    # ── 3. Issue Summary Breakdown ───────────────────────────────────────────
    story.append(Paragraph("Issue Breakdown", h1_style))

    sev = report.severity_breakdown
    cat = report.category_breakdown

    breakdown_data = [
        [
            Paragraph("<b>Severity</b>", label_style),
            Paragraph("<b>Count</b>", label_style),
            Paragraph("<b>Category</b>", label_style),
            Paragraph("<b>Count</b>", label_style),
        ],
        [
            Paragraph("<font color='#b91c1c'><b>● Critical</b></font>", field_style),
            Paragraph(str(sev.critical), field_style),
            Paragraph("Bugs & Logic Errors", field_style),
            Paragraph(str(cat.bugs), field_style),
        ],
        [
            Paragraph("<font color='#c2410c'><b>● High</b></font>", field_style),
            Paragraph(str(sev.high), field_style),
            Paragraph("Security Vulnerabilities", field_style),
            Paragraph(str(cat.security), field_style),
        ],
        [
            Paragraph("<font color='#a16207'><b>● Medium</b></font>", field_style),
            Paragraph(str(sev.medium), field_style),
            Paragraph("Code Quality & Smells", field_style),
            Paragraph(str(cat.quality), field_style),
        ],
        [
            Paragraph("<font color='#1d4ed8'><b>● Low</b></font>", field_style),
            Paragraph(str(sev.low), field_style),
            Paragraph("<b>Total Issues</b>", label_style),
            Paragraph(f"<b>{report.total_issues}</b>", label_style),
        ],
    ]

    breakdown_table = Table(breakdown_data, colWidths=[2.2 * inch, 1.3 * inch, 2.2 * inch, 1.3 * inch])
    breakdown_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#f1f5f9")),
        ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
        ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ("LEFTPADDING", (0, 0), (-1, -1), 8),
        ("RIGHTPADDING", (0, 0), (-1, -1), 8),
    ]))
    story.append(breakdown_table)
    story.append(Spacer(1, 14))

    # ── 4. File Quality Metrics Table ────────────────────────────────────────
    if report.file_metrics:
        story.append(Paragraph("File-Level Quality & Maintainability", h1_style))
        metrics_header = [
            Paragraph("<b>File Path</b>", label_style),
            Paragraph("<b>Lang</b>", label_style),
            Paragraph("<b>LOC</b>", label_style),
            Paragraph("<b>Complexity</b>", label_style),
            Paragraph("<b>MI</b>", label_style),
            Paragraph("<b>Rank</b>", label_style),
        ]
        metrics_rows = [metrics_header]
        for fm in report.file_metrics[:12]:  # Limit top 12 files for compact summary
            metrics_rows.append([
                Paragraph(f"<font size=7.5>{fm.file_path}</font>", field_style),
                Paragraph(fm.language, field_style),
                Paragraph(str(fm.loc), field_style),
                Paragraph(str(fm.cyclomatic_complexity) if fm.cyclomatic_complexity is not None else "—", field_style),
                Paragraph(f"{fm.maintainability_index:.0f}" if fm.maintainability_index is not None else "—", field_style),
                Paragraph(f"<b>{fm.maintainability_rank or 'A'}</b>", field_style),
            ])

        metrics_table = Table(metrics_rows, colWidths=[3.0 * inch, 0.9 * inch, 0.7 * inch, 0.9 * inch, 0.7 * inch, 0.8 * inch])
        metrics_table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#f1f5f9")),
            ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
            ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ("LEFTPADDING", (0, 0), (-1, -1), 6),
            ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ]))
        story.append(metrics_table)
        story.append(Spacer(1, 16))

    # ── 5. Detailed Explainable Findings (Grouped by Severity) ───────────────
    story.append(PageBreak())
    story.append(Paragraph("Detailed Explainable Findings", title_style))
    story.append(Paragraph("Issues are ranked and prioritized by Severity (Critical → High → Medium → Low).", subtitle_style))
    story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#94a3b8"), spaceAfter=12))

    severities = ["Critical", "High", "Medium", "Low"]
    issues_by_sev = {s: [] for s in severities}
    for iss in report.issues:
        if iss.severity in issues_by_sev:
            issues_by_sev[iss.severity].append(iss)

    for sev_level in severities:
        grp = issues_by_sev[sev_level]
        if not grp:
            continue

        header_color = {
            "Critical": "#b91c1c",
            "High": "#c2410c",
            "Medium": "#a16207",
            "Low": "#1d4ed8",
        }[sev_level]

        story.append(Paragraph(f"<font color='{header_color}'>● {sev_level} Priority Issues ({len(grp)})</font>", h1_style))

        for issue in grp:
            card_elements = []

            # Issue header row
            card_header_text = (
                f"<b>[{issue.id}] {issue.title}</b> — <i>{issue.category}</i> "
                f"({issue.file_name}:{issue.line_number or '—'})"
            )
            card_elements.append(Paragraph(card_header_text, h2_style))

            # 4 Explanatory Blocks Table
            details_table_data = [
                [
                    Paragraph("<b>1. Explanation:</b>", label_style),
                    Paragraph(issue.explanation, field_style)
                ],
                [
                    Paragraph("<b>2. Why It Matters:</b>", label_style),
                    Paragraph(issue.why_it_matters, field_style)
                ],
                [
                    Paragraph("<b>3. Possible Impact:</b>", label_style),
                    Paragraph(issue.possible_impact, field_style)
                ],
                [
                    Paragraph("<b>4. Recommended Fix:</b>", label_style),
                    Paragraph(issue.recommendation, field_style)
                ],
            ]

            details_table = Table(details_table_data, colWidths=[1.4 * inch, 5.4 * inch])
            details_table.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#f8fafc")),
                ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
                ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
                ("TOPPADDING", (0, 0), (-1, -1), 3),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
                ("LEFTPADDING", (0, 0), (-1, -1), 6),
                ("RIGHTPADDING", (0, 0), (-1, -1), 6),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ]))
            card_elements.append(details_table)

            # Code Snippet (if available)
            if issue.code_snippet:
                card_elements.append(Spacer(1, 3))
                code_table = Table(
                    [[Paragraph(f"<pre>{issue.code_snippet}</pre>", code_style)]],
                    colWidths=[6.8 * inch]
                )
                code_table.setStyle(TableStyle([
                    ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#0f172a")),
                    ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#334155")),
                    ("TOPPADDING", (0, 0), (-1, -1), 4),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                    ("LEFTPADDING", (0, 0), (-1, -1), 6),
                    ("RIGHTPADDING", (0, 0), (-1, -1), 6),
                ]))
                card_elements.append(code_table)

            card_elements.append(Spacer(1, 8))
            story.append(KeepTogether(card_elements))

    # ── 6. Disclaimer & Audit Notice ─────────────────────────────────────────
    story.append(Spacer(1, 14))
    story.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#cbd5e1"), spaceAfter=10))

    disclaimer_text = (
        "<b>Disclaimer & Methodology:</b> BugSense is an offline, explainable AI-assisted debugging system. "
        "All findings are produced purely via static analysis (AST parsing, pattern matching, Bandit, Radon, and local rule sets) "
        "without executing or evaluating the uploaded software. "
        "Recommendations are provided for developer guidance only and do not automatically mutate source files. "
        "While BugSense identifies common bugs, security vulnerabilities, and anti-patterns, "
        "static analysis cannot mathematically guarantee the detection of all runtime errors or security vulnerabilities."
    )
    story.append(Paragraph(disclaimer_text, ParagraphStyle("Disc", parent=styles["Normal"], fontSize=7.5, leading=10, textColor=colors.HexColor("#64748b"))))

    # Build the document
    doc.build(story, canvasmaker=NumberedCanvas)
    buffer.seek(0)
    return buffer.getvalue()
